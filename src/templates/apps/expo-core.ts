export function babelConfigContent(): string {
  // uniwind exposes ./components, ./metro, ./vite and ./types — there is NO
  // ./babel subpath in its exports map. Listing it made Metro fail on the very
  // first module with ERR_PACKAGE_PATH_NOT_EXPORTED, so `expo start`,
  // `expo export` and `turbo run build` all died before bundling anything.
  // uniwind hooks in through metro.config.js (withUniwind), not through babel.
  return `module.exports = function(api){api.cache(true); return {presets:['babel-preset-expo']};};
`;
}

export function babelConfig(): TemplateFile {
  return file("apps/mobile/babel.config.js", babelConfigContent());
}

export function babelConfigSingle(): TemplateFile {
  return file("babel.config.js", babelConfigContent());
}

