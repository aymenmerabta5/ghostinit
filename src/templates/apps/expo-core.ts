type FeatureInput =
  | boolean
  | AddonInstallerMap
  | Record<string, { inUse: boolean }>
  | BillingProviderName[];

function resolveHasFeature(input: FeatureInput = false, feature: string): boolean {
  if (typeof input === "boolean") return input;
  if (Array.isArray(input)) return false;
  const rec = input as Record<string, { inUse?: boolean }>;
  return Boolean(rec[feature]?.inUse);
}

function resolveHasEve(input: FeatureInput = false): boolean {
  return resolveHasFeature(input, "eve");
}

function resolveHasI18n(input: FeatureInput = false): boolean {
  return resolveHasFeature(input, "i18n");
}

export function uniwindTypesDtsContent(): string {
  // The triple-slash reference is what pulls in uniwind/types, which augments
  // react-native's component props with `className`. Without it the stub silently
  // shadowed uniwind's own generated d.ts and every className={...} on a native
  // component failed with TS2769.
  return `// Generated by Uniwind - do not edit
// This file is auto-generated when running expo start
/// <reference types="uniwind/types" />
declare module "uniwind" {}
`;
}

export function uniwindTypesDts(): TemplateFile {
  return file("apps/mobile/uniwind-types.d.ts", uniwindTypesDtsContent());
}

export function uniwindTypesDtsSingle(): TemplateFile {
  return file("uniwind-types.d.ts", uniwindTypesDtsContent());
}

export function expoCoreFiles(
  runtime: "node" | "bun" = "bun",
  hasEveInput: FeatureInput = false,
  hasI18nInput: FeatureInput = false,
): TemplateFile[] {
  const hasEve = resolveHasEve(hasEveInput);
  const hasI18n = resolveHasI18n(hasI18nInput ?? hasEveInput);
  const effectiveHasI18n = typeof hasEveInput !== "boolean" ? resolveHasI18n(hasEveInput) : hasI18n;
  return [
    webPackageMobile(runtime, hasEve, effectiveHasI18n),
    appJson(),
    babelConfig(),
    metroConfig(),
    file("apps/mobile/global.css", mobileGlobalCssContent()),
    file("apps/mobile/uniwind-types.d.ts", uniwindTypesDtsContent()),
    expoEnvDts(),
    tsconfigMobile(),
    // The `test` script runs `bun test tests`; without this file that directory
    // did not exist and the task exited 1 on every fresh project.
    file(
      "apps/mobile/tests/smoke.test.ts",
      `import { describe, it, expect } from "bun:test";
import appJson from "../app.json";

describe("mobile app config", () => {
  it("declares a scheme so Better Auth deep links resolve", () => {
    expect(typeof appJson.expo.scheme).toBe("string");
    expect(appJson.expo.scheme.length).toBeGreaterThan(0);
  });

  it("registers expo-router as a plugin", () => {
    expect(appJson.expo.plugins).toContain("expo-router");
  });
});
`,
    ),
  ];
}

