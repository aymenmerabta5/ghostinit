import { codeScripts, file, packageJson, tsconfig, type TemplateFile } from "./shared.js";
import { billingApplicationsFiles } from "./billing/applications/billing.js";
import * as v from "./versions.js";

/**
 * The identity module is always emitted — it demonstrates Domain>Capabilities
 * with no external dependencies and is the minimal testable unit. The billing
 * module is emitted whenever billing is selected and demonstrates the full
 * 6-layer chain end-to-end (see longer comment inline). When billing is not
 * selected the `billing` directory must not be emitted, otherwise the generated
 * project would import @repo/billing which does not exist in that corner.
 */
export function modulesPackage(runtime: "node" | "bun" = "bun", hasBilling = true): TemplateFile[] {
  return [
    file(
      "packages/modules/package.json",
      packageJson({
        name: "@repo/modules",
        scripts: codeScripts({ test: runtime === "bun" ? "bun test" : "npm run test:unit" }),
        exports: {
          ".": "./src/index.ts",
          "./*": "./src/*/index.ts",
        },
        dependencies: {
          "@repo/contracts": "workspace:*",
        },
        devDependencies: {
          ...(runtime === "bun" ? { "bun-types": `^${v.runtime.bun}` } : {}),
          typescript: `^${v.typescript.typescript}`,
        },
      }),
    ),
    file(
      "packages/modules/tsconfig.json",
      tsconfig({
        include: ["src/**/*", "tests/**/*"],
        compilerOptions: { types: runtime === "bun" ? ["bun-types"] : ["node"] },
      }),
    ),
    // Sorted alphabetically so the on-disk file matches what `sync` rebuilds.
    // When billing is not selected the billing demo is omitted entirely —
    // otherwise the generated project imports @repo/billing which does not exist
    // in that corner and the generation-matrix fails on "every import resolves".
    ...(() => {
      const exports = hasBilling
        ? `export * as billing from "./billing/index";
export * as identity from "./identity/index";`
        : `export * as identity from "./identity/index";`;
      return [
        file(
          "packages/modules/src/index.ts",
          `// Generated by ghostinit sync. Do not edit manually.
${exports}
`,
        ),
      ];
    })(),
    file(
      "packages/modules/src/identity/index.ts",
      `export * from "./domain/index";\nexport * from "./application/index";\nexport type * from "./ports/index";\n`,
    ),
    file(
      "packages/modules/src/identity/domain/types.ts",
      `export interface UserProfile {\n  id: string;\n  email: string;\n  name: string | null;\n}\n`,
    ),
    file(
      "packages/modules/src/identity/domain/index.ts",
      `export { type UserProfile } from "./types.js";\n`,
    ),
    file(
      "packages/modules/src/identity/application/get-profile.ts",
      `import { type UserProfile } from "../domain/types.js";\n\nexport interface GetProfileInput {\n  userId: string;\n}\n\nexport interface GetProfileDeps {\n  findById: (userId: string) => Promise<UserProfile | null>;\n}\n\nexport async function getProfileUseCase(\n  input: GetProfileInput,\n  deps: GetProfileDeps,\n): Promise<UserProfile | null> {\n  return deps.findById(input.userId);\n}\n`,
    ),
    file(
      "packages/modules/src/identity/application/index.ts",
      `export { getProfileUseCase } from "./get-profile.js";\n`,
    ),
    file(
      "packages/modules/src/identity/ports/index.ts",
      `import type { UserProfile } from "../domain/types.js";\n\nexport interface UserRepository {\n  findById(userId: string): Promise<UserProfile | null>;\n}\n`,
    ),
    file(
      "packages/modules/tests/identity/get-profile.test.ts",
      `import { describe, it, expect } from "bun:test";\nimport { getProfileUseCase } from "../../src/identity/application/get-profile.js";\n\ndescribe("getProfileUseCase", () => {\n  it("returns the profile when found", async () => {\n    const profile = { id: "1", email: "a@example.com", name: "A" };\n    const result = await getProfileUseCase(\n      { userId: "1" },\n      { findById: async () => profile },\n    );\n    expect(result).toEqual(profile);\n  });\n\n  it("returns null when missing", async () => {\n    const result = await getProfileUseCase(\n      { userId: "2" },\n      { findById: async () => null },\n    );\n    expect(result).toBeNull();\n  });\n});\n`,
    ),
    // The billing module is the reference demonstration for the 6-layer chain:
    // app/api/** (or app/api/billing/** in the transport) → @repo/api
    // (oRPC procedures, Transport layer 2) → @repo/modules/billing/application/*
    // (Domain/application layer 3) → @repo/services/billing/* (Capabilities layer 4)
    // → @repo/billing/providers/* (Vendors layer 5) → @repo/database/@repo/config
    // (Supporting layer 6). This is what `ghostinit check` enforces with
    // no-restricted-imports; it is non-vacuous because layers 3,4,5 all import
    // one another directionally.
    //
    // Emitted only when billing is selected, otherwise the generated project
    // imports @repo/billing which does not exist in that corner.
    ...(hasBilling
      ? [
          file(
            "packages/modules/src/billing/index.ts",
            `export * from "./application/index.js";\n`,
          ),
          file(
            "packages/modules/src/billing/application/index.ts",
            `export { createCheckoutUseCase, type CreateCheckoutUseCaseInput } from "./create-checkout.usecase.js";
export { listSubscriptionsUseCase } from "./list-subscriptions.usecase.js";
export { createPortalSessionUseCase, type CreatePortalSessionUseCaseInput, type PortalSessionRecord } from "./create-portal-session.usecase.js";
`,
          ),
          ...billingApplicationsFiles("monorepo"),
        ]
      : []),
  ];
}
