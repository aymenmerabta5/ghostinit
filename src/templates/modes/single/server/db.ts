export function serverDbIndexSingle(includeBilling = true, includeAuth = true): string {
  const authImport = includeAuth ? "import * as authSchema from './schema/auth';" : "";
  const billingImport = includeBilling ? "import * as billingSchema from './schema/billing';" : "";
  const schemaParts = [includeAuth ? "...authSchema" : "", includeBilling ? "...billingSchema" : ""]
    .filter(Boolean)
    .join(", ");
  return [
    "import { drizzle } from 'drizzle-orm/node-postgres';",
    "import { Pool, type PoolConfig } from 'pg';",
    authImport,
    billingImport,
    "",
    "function buildConnectionString(): string {",
    "  if (process.env.DATABASE_URL) return process.env.DATABASE_URL;",
    "  const user = encodeURIComponent(process.env.POSTGRES_USER ?? 'postgres');",
    "  const password = encodeURIComponent(process.env.POSTGRES_PASSWORD ?? '');",
    "  const host = process.env.POSTGRES_HOST ?? 'localhost';",
    "  const port = process.env.POSTGRES_PORT ?? '5432';",
    "  const database = encodeURIComponent(process.env.POSTGRES_DB ?? process.env.APP_NAME ?? 'ghostinit');",
    "  return `postgresql://${user}:${password}@${host}:${port}/${database}`;",
    "}",
    "",
    "function rejectConnectionStringTlsOverrides(connectionString: string): void {",
    "  if (process.env.DATABASE_SSL !== 'true') return;",
    "  const parsed = new URL(connectionString);",
    "  for (const key of parsed.searchParams.keys()) {",
    "    const normalized = key.toLowerCase();",
    "    if (normalized.startsWith('ssl') || normalized === 'uselibpqcompat') {",
    "      throw new Error('DATABASE_URL must not override TLS parameters when DATABASE_SSL=true');",
    "    }",
    "  }",
    "}",
    "",
    "const connectionString = buildConnectionString();",
    "rejectConnectionStringTlsOverrides(connectionString);",
    "",
    "const configuredPoolSize = Number.parseInt(process.env.DATABASE_POOL_SIZE ?? '20', 10);",
    "if (!Number.isSafeInteger(configuredPoolSize) || configuredPoolSize < 1 || configuredPoolSize > 100) {",
    "  throw new Error('DATABASE_POOL_SIZE must be an integer between 1 and 100');",
    "}",
    "const poolConfig: PoolConfig = {",
    "  connectionString,",
    "  max: configuredPoolSize,",
    "  idleTimeoutMillis: 30_000,",
    "};",
    "if (process.env.DATABASE_SSL === 'true') {",
    "  poolConfig.ssl = process.env.DATABASE_SSL_CA",
    "    ? { ca: process.env.DATABASE_SSL_CA, rejectUnauthorized: true }",
    "    : true;",
    "}",
    "const pool = new Pool(poolConfig);",
    "",
    schemaParts
      ? `export const db = drizzle(pool, { schema: { ${schemaParts} } });`
      : "export const db = drizzle(pool);",
    "",
  ].join("\n");
}

