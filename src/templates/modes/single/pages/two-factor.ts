export function singleTwoFactorPageContent(): string {
  return [
    '"use client";',
    "",
    "import * as React from 'react';",
    "import { useRouter } from 'next/navigation';",
    "import { useState } from 'react';",
    "import Link from 'next/link';",
    "import { authClient } from '@/lib/auth-client';",
    "import { Card, CardHeader, CardTitle, CardDescription, CardContent, CardFooter } from '@/components/ui/card';",
    "import { Input } from '@/components/ui/input';",
    "import { Alert, AlertTitle, AlertDescription } from '@/components/ui/alert';",
    "import { Badge } from '@/components/ui/badge';",
    "import { FieldGroup, Field, FieldLabel, FieldDescription } from '@/components/ui/field';",
    "import { Form, Field as TanStackField, SubmitButton, useForm } from '@/components/ui/form';",
    "",
    "interface TwoFactorForm { code: string; }",
    "",
    "export default function TwoFactorPage(): React.JSX.Element {",
    "  const router = useRouter();",
    "  const [error, setError] = useState<string | null>(null);",
    "  const form = useForm({",
    "    defaultValues: { code: '' } as TwoFactorForm,",
    "    onSubmit: async ({ value }) => {",
    "      setError(null);",
    "      const result = await authClient.twoFactor.verifyTotp({ code: value.code, trustDevice: true });",
    "      if (result.error) { setError(result.error.message ?? 'Invalid code'); return; }",
    "      router.push('/dashboard');",
    "    },",
    "  });",
    "  return (",
    "    <main className='min-h-screen flex items-center justify-center p-6 bg-background'>",
    "      <div className='w-full max-w-[420px] flex flex-col gap-6'>",
    "        <Link href='/' className='text-sm text-muted-foreground hover:text-foreground'>← Back to home</Link>",
    "        <Card className='shadow-sm'>",
    "          <CardHeader className='flex flex-col gap-3'>",
    "            <div className='flex items-center gap-2'>",
    "              <Badge variant='secondary'>2FA</Badge>",
    "              <span className='text-xs text-muted-foreground'>TOTP • trust 30d</span>",
    "            </div>",
    "            <CardTitle className='text-2xl tracking-tight'>Two-factor authentication</CardTitle>",
    "            <CardDescription className='max-w-[60ch]'>Enter the 6-digit code from your authenticator app. Secure verification with rate limiting and replay protection.</CardDescription>",
    "          </CardHeader>",
    "          <CardContent className='flex flex-col gap-6'>",
    "            {error ? (<Alert variant='destructive'><AlertTitle>Invalid code</AlertTitle><AlertDescription>{error}</AlertDescription></Alert>) : null}",
    "            <Form form={form} className='flex flex-col gap-6'>",
    "              <FieldGroup>",
    "                <TanStackField form={form} name='code' validators={{ onSubmit: ({ value }) => (/^[0-9]{6}$/.test(value) ? undefined : 'Enter a 6-digit code') }}>{(field) => (<Field data-invalid={field.state.meta.errors.length > 0} className='flex flex-col gap-3'><FieldLabel htmlFor='totp-code' className='text-sm'>Authentication code</FieldLabel><Input id='totp-code' name={field.name} inputMode='numeric' autoComplete='one-time-code' maxLength={6} placeholder='000000' required aria-invalid={field.state.meta.errors.length > 0} value={field.state.value} onChange={(e) => field.handleChange(e.target.value.replace(/[^0-9]/g, '').slice(0, 6))} onBlur={field.handleBlur} className='font-mono tracking-widest text-center text-lg h-12' />{field.state.meta.errors.length > 0 ? <FieldDescription className='text-destructive'>{field.state.meta.errors.join(', ')}</FieldDescription> : <FieldDescription className='max-w-[60ch]'>Open authenticator such as Authy, 1Password, Google Authenticator. Code refreshes every 30s.</FieldDescription>}</Field>)}</TanStackField>",
    "              </FieldGroup>",
    "              <SubmitButton className='w-full'>Verify and continue</SubmitButton>",
    "            </Form>",
    "          </CardContent>",
    "          <CardFooter className='flex justify-between text-sm'>",
    "            <Link href='/sign-in' className='text-muted-foreground hover:text-foreground underline-offset-4 hover:underline'>Back to sign in</Link>",
    "            <Link href='/settings' className='text-muted-foreground hover:text-foreground underline-offset-4 hover:underline'>Recovery codes</Link>",
    "          </CardFooter>",
    "        </Card>",
    "        <p className='text-center text-xs text-muted-foreground max-w-[65ch] mx-auto'>Trust device stores secure httpOnly cookie for 30 days. Rate limited 60/min. Works offline TOTP RFC6238.</p>",
    "      </div>",
    "    </main>",
    "  );",
    "}",
    "",
  ].join("\n");
}

