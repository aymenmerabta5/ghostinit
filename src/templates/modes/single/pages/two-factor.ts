    "          <div className='flex items-center gap-3'>",
    "            <h1 className='text-2xl font-semibold tracking-tight'>Eve Durable Agent</h1>",
    "            <Badge variant='secondary'><span className='flex items-center gap-1.5'><span className='size-1.5 rounded-full bg-primary' /> durable</span></Badge>",
    "          </div>",
    '          <p className="text-sm text-muted-foreground max-w-[65ch] leading-relaxed">Chat uses Eve agent in <code className="rounded bg-muted px-1 py-0.5 font-mono text-xs">agent/</code> — filesystem-first durable backend mounted same-origin via withEve({`{ eveRoot: "./agent" }`}). Tools: scaffold_module, check_architecture, sync_registries, list_modules, db_migrate.</p>',
